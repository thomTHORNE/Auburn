// Builds Spec/Visual Design/components.js from every Spec/Visual Design/components/<name>/component.html.
//
// Each component.html holds one <template id="auburn-<name>">: the component's markup, with
//   {{name}}                               a hole for text, from the element's data-name attribute
//   <template data-each="list">…</template>  a repeat over a list: the logic's array, or data-list split on "|",
//                                          with {{item}} or {{item.field}} inside
//   <style>                                its rules, which switch variants on the element's data attributes
//   <script type="text/x-logic">           optional: function (data) returning more holes, such as a list
//   {{uid}}                                a value unique to each element, for ids inside it
// components.js defines each as a custom element: <auburn-widget data-kind="goals" …>. The element keeps
// its data attributes and takes its name as a class, so the same rules match it here and on the canvas.
// Run from the repository root after any change to a component: node Tools/build-components.mjs

import { readdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = 'Spec/Visual Design';

export function readComponent(path) {
  const src = readFileSync(path, 'utf8');
  const m = src.match(/<template id="(auburn-[a-z-]+)" data-props="([^"]*)" data-text="([^"]*)">\n([\s\S]*?)\n<\/template>\n<section/);
  if (!m) throw new Error(`${path}: no component template`);
  let body = m[4];
  const css = (body.match(/<style>\n([\s\S]*?)\n<\/style>\n/) || [])[1] || '';
  const logic = (body.match(/<script type="text\/x-logic">\n([\s\S]*?)\n<\/script>\n/) || [])[1] || '';
  body = body.replace(/<style>\n[\s\S]*?\n<\/style>\n/, '').replace(/<script type="text\/x-logic">\n[\s\S]*?\n<\/script>\n/, '');
  // "kind: rest goals cardio; width: full half" → { kind: ['rest', 'goals', 'cardio'], width: ['full', 'half'] }
  const props = Object.fromEntries(m[2].split(';').map((p) => p.trim()).filter(Boolean)
    .map((p) => { const [k, v] = p.split(':'); return [k.trim(), v.trim().split(/\s+/)]; }));
  const states = [...src.matchAll(/<section id="([a-z-]+)">\n<h2>([^<]*)<\/h2>\n<div class="frame" style="([^"]*)">([\s\S]*?)<\/div>\n<\/section>/g)]
    .map(([, id, label, frame, inst]) => ({ id, label, frame, inst }));
  return { tag: m[1], props, text: m[3].split(/\s+/).filter(Boolean), css, logic, html: body, states };
}

export function components() {
  const dir = join(ROOT, 'components');
  return readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(dir, d.name, 'component.html')))
    .map((d) => ({ name: d.name, ...readComponent(join(dir, d.name, 'component.html')) }));
}

// The runtime: fills a template from an element's data, then lets nested components upgrade themselves.
const runtime = `function fill(html, data) {
  var esc = function (v) { return String(v == null ? '' : v).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;'); };
  var look = function (path, d) { return path.split('.').reduce(function (o, k) { return o == null ? o : o[k]; }, d); };
  html = html.replace(/<template data-each="([a-z0-9]+)">([\\s\\S]*?)<\\/template>/g, function (_, name, inner) {
    var list = data[name];
    if (typeof list === 'string') list = list ? list.split('|') : [];
    return (list || []).map(function (item) { return fill(inner, Object.assign({}, data, { item: item })); }).join('');
  });
  return html.replace(/\\{\\{([a-z0-9.]+)\\}\\}/g, function (_, path) { return esc(look(path, data)); });
}`;

export function build() {
  const list = components();
  const defs = list.map((c) => `  ${JSON.stringify(c.tag)}: { html: ${JSON.stringify(c.html)}, logic: ${c.logic || 'null'} }`).join(',\n');
  const css = list.map((c) => c.css).filter(Boolean).join('\n');
  const js = `// Generated by Tools/build-components.mjs from every component.html in components/. Never edited.
(function () {
var base = new URL('.', document.currentScript.src).href;
var count = 0;
var C = {
${defs}
};
${runtime}
var style = document.createElement('style');
style.textContent = ${JSON.stringify(css)};
document.head.appendChild(style);
Object.keys(C).forEach(function (tag) {
  customElements.define(tag, class extends HTMLElement {
    connectedCallback() {
      if (this.dataset.filled) return;
      var data = Object.assign({ assets: base, uid: 'c' + (++count) }, this.dataset);
      if (C[tag].logic) Object.assign(data, C[tag].logic(data));
      this.classList.add(tag);
      this.dataset.filled = '';
      this.innerHTML = fill(C[tag].html, data);
    }
  });
});
})();
`;
  writeFileSync(join(ROOT, 'components.js'), js);
  return list;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log('Built components.js:', build().map((c) => c.tag).join(', '));
}
